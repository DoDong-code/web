// Generates a content-hash map for every file under public/.
//
// The map powers URL versioning in src/lib/assetCdn.ts: every asset URL gets a
// `?v=<md5-prefix>` suffix derived from the file bytes, so
//   - unchanged file  -> same URL -> browser keeps its cached copy forever
//   - changed file    -> new URL  -> browser refetches automatically
//
// No file is renamed and nothing moves: the hash only lives in the query
// string and COS happily ignores unknown query parameters (verified: requesting
// an object with `?v=anything` returns 200 and the same ETag).
//
// Usage:
//   node scripts/generate-asset-hash-map.mjs
//
// Optional:
//   --source <dir>   defaults to public
//   --out <file>     defaults to src/lib/assetHashMap.generated.ts
//   --length <n>     hash prefix length, defaults to 12
import crypto from 'node:crypto';
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

function flag(name, fallback) {
  const index = process.argv.indexOf(name);
  return index >= 0 && index + 1 < process.argv.length ? process.argv[index + 1] : fallback;
}

const root = process.cwd();
const sourceDir = path.resolve(root, flag('--source', 'public'));
const outFile = path.resolve(root, flag('--out', 'src/lib/assetHashMap.generated.ts'));
const hashLength = Number(flag('--length', '12'));

async function walk(dir) {
  const files = [];
  let entries;
  try {
    entries = await fsp.readdir(dir, {withFileTypes: true});
  } catch {
    return files;
  }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full)));
    else files.push(full);
  }
  return files;
}

async function hashFile(file) {
  const hash = crypto.createHash('md5');
  const stream = fs.createReadStream(file);
  for await (const chunk of stream) hash.update(chunk);
  return hash.digest('hex').slice(0, hashLength);
}

const files = await walk(sourceDir);

if (files.length === 0) {
  console.log(`No files found under ${path.relative(root, sourceDir)}/ - writing an empty asset hash map.`);
}

const entries = [];
for (const file of files) {
  const relative = path.relative(sourceDir, file).split(path.sep).join('/');
  entries.push([`/${relative}`, await hashFile(file)]);
}
entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));

const body = entries.map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`).join('\n');
const contents = `// AUTO-GENERATED by scripts/generate-asset-hash-map.mjs - do not edit.
// Key is the POSIX path inside public/, value is the md5 prefix of its bytes.
// Regenerated automatically by \`npm run build\` / \`npm run dev\`.
export const ASSET_HASH_MAP: Record<string, string> = {
${body}
};

export default ASSET_HASH_MAP;
`;

const previous = await fsp.readFile(outFile, 'utf8').catch(() => null);
if (previous !== contents) {
  await fsp.mkdir(path.dirname(outFile), {recursive: true});
  await fsp.writeFile(outFile, contents);
  console.log(`Wrote ${entries.length} asset hashes -> ${path.relative(root, outFile)}`);
} else {
  console.log(`Asset hash map unchanged (${entries.length} entries) - skipped write`);
}
